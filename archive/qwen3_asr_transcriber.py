def main(output_srt=True, language=None):
    print("\n" + "="*60)
    print("🚀 Qwen3-ASR-1.7B 終極長音訊優化版 (支援 1 小時以上)")
    print("="*60)

    wav = None
    try:
        gpu_type, cfg, attn_impl = GPUOptimizer.detect()
        dev = "cuda:0" if torch.cuda.is_available() else "cpu"

        print(f"\n📤 請上傳音訊檔案 (支援 mp3, wav, m4a, mp4)...")
        uploaded = files.upload()
        if not uploaded: return
        src = list(uploaded.keys())[0]

        wav = AudioProcessor.convert(src)

        asr = Qwen3ASR(dev, cfg["dtype"], cfg["batch"], attn_impl)
        asr.load()

        segs = asr.transcribe(wav, cfg["chunk"], language)

        txt, srt_file = save_results(segs, src, output_srt)
        if txt:
            print(f"\n📥 準備下載...")
            files.download(txt)
            if srt_file: files.download(srt_file)

    except Exception as e:
        print(f"\n❌ 發生錯誤: {e}")
        import traceback
        traceback.print_exc()

    finally:
        if wav and os.path.exists(wav): os.remove(wav)
        gc.collect()
        if torch.cuda.is_available():
            torch.cuda.empty_cache()
            print("🧹 GPU 記憶體已安全清理完成。")

if __name__ == "__main__":
    main()