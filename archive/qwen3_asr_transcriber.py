class Qwen3ASR:
    MODEL = "Qwen/Qwen3-ASR-1.7B"
    ALIGNER = "Qwen/Qwen3-ForcedAligner-0.6B"

    def __init__(self, device, dtype, batch_size, attn_impl):
        self.device = device
        self.dtype = dtype
        self.batch_size = batch_size
        self.attn_impl = attn_impl
        self.model = None

    def load(self):
        print(f"⏳ 正在載入模型 ({self.attn_impl} 加速中)...")
        t0 = time.time()

        model_kwargs = {
            "pretrained_model_name_or_path": self.MODEL,
            "dtype": self.dtype,
            "device_map": self.device,
            "max_inference_batch_size": self.batch_size,
            "max_new_tokens": 512,
            "forced_aligner": self.ALIGNER,
            "forced_aligner_kwargs": {"dtype": self.dtype, "device_map": self.device}
        }

        if self.attn_impl != "None":
            model_kwargs["attn_implementation"] = self.attn_impl

        self.model = Qwen3ASRModel.from_pretrained(**model_kwargs)
        print(f"✅ 模型載入完成 ({time.time()-t0:.1f}s)")
        return self

    def transcribe(self, wav_path, chunk_sec=30, lang=None):
        print(f"\n🚀 開始轉錄 (Batch Size: {self.batch_size})...")

        audio, sr = sf.read(wav_path)
        if len(audio.shape) > 1: audio = audio.mean(axis=1)
        total_dur = len(audio) / sr

        chunks_data = AudioProcessor.smart_chunking(audio, sr, chunk_sec)
        n_chunks = len(chunks_data)

        # 顯示友善時間
        h, m = int(total_dur // 3600), int((total_dur % 3600) // 60)
        print(f"   總時長: {h}小時 {m}分鐘 ({total_dur:.1f}s) | 有效切片數: {n_chunks}")

        final_segments = []
        t0 = time.time()

        for i in range(0, n_chunks, self.batch_size):
            batch_items = chunks_data[i : i + self.batch_size]
            batch_audios = [item["audio"] for item in batch_items]

            progress = min(i + self.batch_size, n_chunks)
            print(f"\r   處理中: {progress}/{n_chunks} ({(progress/n_chunks)*100:.1f}%)", end="", flush=True)

            try:
                results = self.model.transcribe(
                    audio=batch_audios,
                    language=lang,
                    return_time_stamps=True
                )

                if not isinstance(results, list): results = [results]

                for j, res in enumerate(results):
                    if res and res.text and res.text.strip():
                        final_segments.append(TimestampedSegment(
                            start_time=batch_items[j]["start"],
                            end_time=batch_items[j]["end"],
                            text=res.text.strip(),
                            language=res.language if hasattr(res, 'language') else ""
                        ))
            except Exception as e:
                print(f"\n   ⚠️ Batch 推理錯誤，嘗試降級單筆處理: {str(e)[:50]}")
                for j, b_audio in enumerate(batch_audios):
                     try:
                         res = self.model.transcribe(audio=b_audio, language=lang, return_time_stamps=True)[0]
                         if res.text and res.text.strip():
                             final_segments.append(TimestampedSegment(
                                start_time=batch_items[j]["start"],
                                end_time=batch_items[j]["end"],
                                text=res.text.strip(),
                                language=res.language if hasattr(res, 'language') else ""
                             ))
                     except Exception:
                         pass

            # 【防護 2】長音訊防護機制：每處理 5 個 Batch 輕度清理 CPU/GPU 垃圾
            # 不使用 empty_cache 避免大掉速，只做 gc.collect 避免變數殘留
            if (i // self.batch_size) % 5 == 0:
                gc.collect()

        elapsed = time.time() - t0
        print(f"\n\n✅ 轉錄完成！耗時: {elapsed:.1f}s (速度比: {total_dur/elapsed:.1f}x)")
        return final_segments

