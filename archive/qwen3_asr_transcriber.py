@dataclass
class TimestampedSegment:
    start_time: float
    end_time: float
    text: str
    language: str = ""

    def format_time(self, seconds: float, srt: bool = False) -> str:
        h, m = int(seconds // 3600), int((seconds % 3600) // 60)
        s = seconds % 60
        if srt:
            return f"{h:02d}:{m:02d}:{s:06.3f}".replace('.', ',')
        return f"{h:02d}:{m:02d}:{int(s):02d}"

    def to_timestamp_line(self) -> str:
        lang = f" [{self.language}]" if self.language else ""
        return f"[{self.format_time(self.start_time)} - {self.format_time(self.end_time)}]{lang} {self.text}"

    def to_srt_block(self, idx: int) -> str:
        return f"{idx}\n{self.format_time(self.start_time, True)} --> {self.format_time(self.end_time, True)}\n{self.text}\n"

