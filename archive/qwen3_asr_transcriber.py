class GPUOptimizer:
    CONFIGS = {
        "H100": {"dtype": torch.bfloat16, "chunk": 30, "batch": 48, "desc": "H100-80GB (Monster)"},
        "A100-80": {"dtype": torch.bfloat16, "chunk": 30, "batch": 48, "desc": "A100-80GB (Ultra)"},
        "A100-40": {"dtype": torch.bfloat16, "chunk": 30, "batch": 24, "desc": "A100-40GB (High)"},
        "L40":  {"dtype": torch.bfloat16, "chunk": 30, "batch": 32, "desc": "L40-48GB (Ada)"},
        "L4":   {"dtype": torch.bfloat16, "chunk": 30, "batch": 12, "desc": "L4-24GB (Ada)"},
        "T4":   {"dtype": torch.float16,  "chunk": 28, "batch": 4,  "desc": "T4-16GB (Standard)"},
        "CPU":  {"dtype": torch.float32,  "chunk": 20, "batch": 1,  "desc": "CPU (Slow)"},
    }

    @staticmethod
    def detect():
        if not torch.cuda.is_available():
            print("⚠️ 未偵測到 GPU，將切換至 CPU 模式 (極慢)")
            return "CPU", GPUOptimizer.CONFIGS["CPU"], "None"

        name = torch.cuda.get_device_name(0)
        vram_gb = torch.cuda.get_device_properties(0).total_memory / (1024**3)
        capability = torch.cuda.get_device_capability(0)

        # 【防護 1】動態降級 SDPA，解決 flash_attn 缺失的報錯
        attn_impl = "sdpa" # PyTorch 原生加速，不需安裝額外套件
        if capability[0] >= 8:
            try:
                import flash_attn
                attn_impl = "flash_attention_2"
            except ImportError:
                print("💡 提示：支援 FlashAttention，但未安裝套件。已自動切換至原生 sdpa 加速 (速度極快)！")

        print(f"🔍 硬體偵測: {name} | VRAM: {vram_gb:.1f}GB | Compute: {capability}")
        print(f"⚡ Attention 機制: {attn_impl}")

        key = "T4"
        if "H100" in name or capability[0] >= 9: key = "H100"
        elif "L40" in name or (capability[0] == 8 and capability[1] == 9 and vram_gb > 40): key = "L40"
        elif "L4" in name or (capability[0] == 8 and capability[1] == 9): key = "L4"
        elif "A100" in name: key = "A100-80" if vram_gb > 70 else "A100-40"
        elif "T4" in name or capability[0] == 7: key = "T4"

        cfg = GPUOptimizer.CONFIGS[key]
        print(f"✅ 優化配置: {cfg['desc']} (Batch: {cfg['batch']}, Dtype: {cfg['dtype']})")
        return key, cfg, attn_impl

