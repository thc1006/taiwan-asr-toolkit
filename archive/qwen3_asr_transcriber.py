def save_results(segs, name, srt=True):
    if not segs:
        print("⚠️ 無內容可儲存")
        return None, None

    base = os.path.splitext(os.path.basename(name))[0]
    txt_path = f"/content/{base}_transcript.txt"
    srt_path = f"/content/{base}.srt" if srt else None

    with open(txt_path, "w", encoding="utf-8") as f:
        for s in segs: f.write(s.to_timestamp_line() + "\n")
    print(f"💾 TXT 已儲存: {txt_path}")

    if srt:
        with open(srt_path, "w", encoding="utf-8") as f:
            for i, s in enumerate(segs, 1): f.write(s.to_srt_block(i) + "\n")
        print(f"💾 SRT 已儲存: {srt_path}")

    return txt_path, srt_path

