class AudioProcessor:
    @staticmethod
    def convert(src: str):
        print("\n🎵 轉換音檔格式 (16kHz Mono)... 這對於 1 小時音訊可能需要 1~2 分鐘")
        with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as f:
            wav = f.name

        cmd = ["ffmpeg", "-y", "-i", src, "-ar", "16000", "-ac", "1", "-c:a", "pcm_s16le", "-loglevel", "error", wav]
        subprocess.run(cmd, check=True, capture_output=True)
        return wav

    @staticmethod
    def smart_chunking(audio_array: np.ndarray, sr: int = 16000, max_chunk_sec: int = 30) -> List[Dict]:
        print("🧠 執行 Silero VAD 智慧切片 (正掃描全段音訊中)...")
        # 確保 VAD 模型載入在 CPU，避免吃掉 GPU 寶貴的 VRAM
        vad_model, utils = torch.hub.load(repo_or_dir='snakers4/silero-vad',
                                          model='silero_vad',
                                          force_reload=False,
                                          trust_repo=True)
        get_speech_timestamps = utils[0]

        audio_tensor = torch.from_numpy(audio_array).float()

        # 使用 VAD 抓取語音區段
        speech_timestamps = get_speech_timestamps(audio_tensor, vad_model, sampling_rate=sr)

        chunks_data = []
        current_start_sample = -1
        current_length_samples = 0
        max_samples = max_chunk_sec * sr

        for ts in speech_timestamps:
            start_s, end_s = ts['start'], ts['end']
            segment_length = end_s - start_s

            if segment_length > max_samples:
                for i in range(start_s, end_s, max_samples):
                    sub_end = min(i + max_samples, end_s)
                    chunks_data.append({
                        "audio": (audio_array[i:sub_end], sr),
                        "start": i / sr,
                        "end": sub_end / sr
                    })
                continue

            if current_length_samples + segment_length > max_samples and current_start_sample != -1:
                end_sample = current_start_sample + current_length_samples
                chunks_data.append({
                    "audio": (audio_array[current_start_sample:end_sample], sr),
                    "start": current_start_sample / sr,
                    "end": end_sample / sr
                })
                current_start_sample = start_s
                current_length_samples = segment_length
            else:
                if current_start_sample == -1:
                    current_start_sample = start_s
                current_length_samples = end_s - current_start_sample

        if current_start_sample != -1:
            end_sample = current_start_sample + current_length_samples
            chunks_data.append({
                "audio": (audio_array[current_start_sample:end_sample], sr),
                "start": current_start_sample / sr,
                "end": end_sample / sr
            })

        # 釋放 VAD 佔用的 RAM
        del vad_model, audio_tensor
        gc.collect()

        return chunks_data

